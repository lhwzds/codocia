/// File-level import edges for Python, Rust, and JS/TS sources.
pub fn import_edges<'a>(repo: &Path, files: &[&'a String]) -> Vec<(&'a str, &'a str)> {
    let python = PythonIndex::new(files);
    let rust = RustIndex::new(repo, files);
    let go = GoIndex::new(repo, files);
    let c = CIndex::new(files);
    let known: BTreeSet<&str> = files.iter().map(|f| f.as_str()).collect();
    let mut edges = Vec::new();
    for file in files {
        let path = file.as_str();
        let Some(ext) = path.rsplit_once('.').map(|(_, e)| e) else {
            continue;
        };
        let c_like = matches!(
            ext,
            "c" | "h" | "cc" | "cpp" | "cxx" | "hpp" | "hh" | "cu" | "cuh" | "m" | "mm"
        );
        if !c_like
            && !matches!(
                ext,
                "py" | "rs" | "ts" | "tsx" | "js" | "jsx" | "mjs" | "go"
            )
        {
            continue;
        }
        let Ok(text) = fs::read_to_string(repo.join(path)) else {
            continue;
        };
        let mut targets: BTreeSet<&str> = BTreeSet::new();
        match ext {
            "py" => {
                for module in python_imports(&text, path) {
                    if let Some(target) = python.resolve(&module) {
                        targets.insert(target);
                    }
                }
            }
            "rs" => {
                for target in rust.resolve_all(&text, path) {
                    targets.insert(target);
                }
            }
            "go" => {
                for spec in go_imports(&text) {
                    if let Some(target) = go.resolve(&spec) {
                        targets.insert(target);
                    }
                }
            }
            _ if c_like => {
                for spec in c_includes(&text) {
                    if let Some(target) = c.resolve(path, &spec) {
                        targets.insert(target);
                    }
                }
            }
            _ => {
                for spec in js_imports(&text) {
                    if let Some(target) = resolve_js(path, &spec, &known) {
                        targets.insert(target);
                    }
                }
            }
        }
        for target in targets {
            if target != path {
                edges.push((path, target));
            }
        }
    }
    edges
}

struct PythonIndex<'a> {
    /// Dotted module suffix -> file; `None` when ambiguous.
    modules: HashMap<String, Option<&'a str>>,
}

impl<'a> PythonIndex<'a> {
    fn new(files: &[&'a String]) -> Self {
        let mut modules: HashMap<String, Option<&'a str>> = HashMap::new();
        for file in files {
            let Some(stem) = file.strip_suffix(".py") else {
                continue;
            };
            let mut parts: Vec<&str> = stem.split('/').collect();
            if parts.last() == Some(&"__init__") {
                parts.pop();
            }
            for start in 0..parts.len() {
                let key = parts[start..].join(".");
                modules
                    .entry(key)
                    .and_modify(|v| {
                        if *v != Some(file.as_str()) {
                            *v = None;
                        }
                    })
                    .or_insert(Some(file.as_str()));
            }
        }
        Self { modules }
    }

    /// Longest dotted prefix of `module` that names exactly one file.
    fn resolve(&self, module: &str) -> Option<&'a str> {
        let parts: Vec<&str> = module.split('.').collect();
        for end in (2..=parts.len()).rev() {
            if let Some(found) = self.modules.get(&parts[..end].join(".")) {
                return *found;
            }
        }
        None
    }
}

/// Imported module names, with relative imports made absolute by path.
fn python_imports(text: &str, path: &str) -> Vec<String> {
    let mut package: Vec<&str> = path.trim_end_matches(".py").split('/').collect();
    package.pop();
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.trim_start();
        if let Some(rest) = line.strip_prefix("from ") {
            let Some((module, names)) = rest.split_once(" import ") else {
                continue;
            };
            let module = module.trim();
            let dots = module.chars().take_while(|c| *c == '.').count();
            let base = if dots > 0 {
                if dots - 1 > package.len() {
                    continue;
                }
                let mut parts = package[..package.len() - (dots - 1)].to_vec();
                let tail = &module[dots..];
                if !tail.is_empty() {
                    parts.extend(tail.split('.'));
                }
                parts.join(".")
            } else {
                module.to_string()
            };
            // `from pkg import sub` may import a submodule.
            for name in names.trim_start_matches('(').split(',') {
                let name = name.split_whitespace().next().unwrap_or("");
                if name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !name.is_empty() {
                    out.push(format!("{base}.{name}"));
                }
            }
            out.push(base);
        } else if let Some(rest) = line.strip_prefix("import ") {
            for item in rest.split(',') {
                if let Some(module) = item.split_whitespace().next() {
                    out.push(module.to_string());
                }
            }
        }
    }
    out
}

struct RustIndex<'a> {
    /// Crate name (underscored) -> crate directory.
    crates: HashMap<String, String>,
    files: BTreeSet<&'a str>,
}

impl<'a> RustIndex<'a> {
    fn new(repo: &Path, files: &[&'a String]) -> Self {
        let mut crates = HashMap::new();
        for file in files {
            if let Some(dir) = file.strip_suffix("Cargo.toml") {
                let dir = dir.trim_end_matches('/').to_string();
                if let Ok(text) = fs::read_to_string(repo.join(file.as_str()))
                    && let Some(name) = cargo_package_name(&text)
                {
                    crates.insert(name.replace('-', "_"), dir);
                }
            }
        }
        Self {
            crates,
            files: files.iter().map(|f| f.as_str()).collect(),
        }
    }

    fn crate_dir(&self, path: &str) -> Option<&str> {
        self.crates
            .values()
            .filter(|dir| dir.is_empty() || path.starts_with(&format!("{dir}/")))
            .max_by_key(|dir| dir.len())
            .map(String::as_str)
    }

    fn module_file(&self, src: &str, parts: &[&str]) -> Option<&'a str> {
        for end in (1..=parts.len()).rev() {
            let stem = format!("{src}/{}", parts[..end].join("/"));
            for candidate in [format!("{stem}.rs"), format!("{stem}/mod.rs")] {
                if let Some(found) = self.files.get(candidate.as_str()) {
                    return Some(found);
                }
            }
        }
        None
    }

    fn resolve_all(&self, text: &str, path: &str) -> Vec<&'a str> {
        let mut out = Vec::new();
        let crate_dir = self.crate_dir(path);
        let src = crate_dir.map(|d| {
            if d.is_empty() {
                "src".to_string()
            } else {
                format!("{d}/src")
            }
        });
        for line in text.lines() {
            let line = line.trim_start();
            let Some(rest) = line
                .strip_prefix("pub use ")
                .or_else(|| line.strip_prefix("use "))
            else {
                continue;
            };
            let parts: Vec<&str> = rest
                .split("::")
                .map(|p| p.trim_end_matches(';').trim())
                .take_while(|p| p.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'))
                .collect();
            let Some(first) = parts.first() else { continue };
            let found = match *first {
                "crate" => src
                    .as_deref()
                    .and_then(|s| self.module_file(s, &parts[1..])),
                "super" | "self" => {
                    let dir = path.rsplit_once('/').map(|(d, _)| d).unwrap_or("");
                    let dir = if *first == "super" && !path.ends_with("/mod.rs") {
                        dir.to_string()
                    } else if *first == "super" {
                        dir.rsplit_once('/')
                            .map(|(d, _)| d)
                            .unwrap_or("")
                            .to_string()
                    } else {
                        dir.to_string()
                    };
                    self.module_file(&dir, &parts[1..])
                }
                name => self.crates.get(name).and_then(|dir| {
                    let src = if dir.is_empty() {
                        "src".to_string()
                    } else {
                        format!("{dir}/src")
                    };
                    self.module_file(&src, &parts[1..])
                        .or_else(|| self.files.get(format!("{src}/lib.rs").as_str()).copied())
                }),
            };
            if let Some(found) = found {
                out.push(found);
            }
        }
        out
    }
}

/// Go imports name packages (directories); a package resolves to its first
/// non-test file so the edge lands in the right area.
struct GoIndex<'a> {
    /// (module path, module directory), longest first.
    modules: Vec<(String, String)>,
    package_files: BTreeMap<String, &'a str>,
}

impl<'a> GoIndex<'a> {
    fn new(repo: &Path, files: &[&'a String]) -> Self {
        let mut modules = Vec::new();
        let mut package_files: BTreeMap<String, &'a str> = BTreeMap::new();
        for file in files {
            if let Some(dir) = file.strip_suffix("go.mod") {
                if let Ok(text) = fs::read_to_string(repo.join(file.as_str()))
                    && let Some(module) =
                        text.lines().find_map(|l| l.trim().strip_prefix("module "))
                {
                    modules.push((
                        module.trim().to_string(),
                        dir.trim_end_matches('/').to_string(),
                    ));
                }
            } else if file.ends_with(".go") && !file.ends_with("_test.go") {
                let dir = file
                    .rsplit_once('/')
                    .map(|(d, _)| d)
                    .unwrap_or("")
                    .to_string();
                package_files.entry(dir).or_insert(file.as_str());
            }
        }
        modules.sort_by_key(|(m, _)| std::cmp::Reverse(m.len()));
        Self {
            modules,
            package_files,
        }
    }

    fn resolve(&self, spec: &str) -> Option<&'a str> {
        let (module, dir) = self
            .modules
            .iter()
            .find(|(m, _)| spec == m || spec.starts_with(&format!("{m}/")))?;
        let rest = spec[module.len()..].trim_start_matches('/');
        let target = match (dir.is_empty(), rest.is_empty()) {
            (true, _) => rest.to_string(),
            (false, true) => dir.clone(),
            (false, false) => format!("{dir}/{rest}"),
        };
        self.package_files.get(&target).copied()
    }
}

fn go_imports(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_block = false;
    for line in text.lines() {
        let line = line.trim();
        if in_block {
            if line.starts_with(')') {
                in_block = false;
                continue;
            }
        } else if let Some(rest) = line.strip_prefix("import") {
            let rest = rest.trim();
            if rest.starts_with('(') {
                in_block = true;
                continue;
            }
            if let Some(spec) = quoted(rest) {
                out.push(spec);
            }
            continue;
        } else {
            continue;
        }
        if let Some(spec) = quoted(line) {
            out.push(spec);
        }
    }
    out
}

fn quoted(text: &str) -> Option<String> {
    let start = text.find('"')?;
    let end = text[start + 1..].find('"')?;
    Some(text[start + 1..start + 1 + end].to_string())
}

/// C-family `#include` resolution: relative to the including file first,
/// then a unique path-suffix match anywhere in the repository.
struct CIndex<'a> {
    by_name: HashMap<&'a str, Vec<&'a str>>,
    known: BTreeSet<&'a str>,
}

impl<'a> CIndex<'a> {
    fn new(files: &[&'a String]) -> Self {
        let mut by_name: HashMap<&'a str, Vec<&'a str>> = HashMap::new();
        for file in files {
            let name = file.rsplit('/').next().unwrap_or(file);
            by_name.entry(name).or_default().push(file.as_str());
        }
        Self {
            by_name,
            known: files.iter().map(|f| f.as_str()).collect(),
        }
    }

    fn resolve(&self, from: &str, spec: &str) -> Option<&'a str> {
        let mut parts: Vec<&str> = from.split('/').collect();
        parts.pop();
        for segment in spec.split('/') {
            match segment {
                "." | "" => {}
                ".." => {
                    parts.pop();
                }
                other => parts.push(other),
            }
        }
        if let Some(found) = self.known.get(parts.join("/").as_str()) {
            return Some(found);
        }
        let name = spec.rsplit('/').next().unwrap_or(spec);
        let candidates: Vec<&&'a str> = self
            .by_name
            .get(name)?
            .iter()
            .filter(|p| **p == spec || p.ends_with(&format!("/{spec}")))
            .collect();
        (candidates.len() == 1).then(|| *candidates[0])
    }
}

fn c_includes(text: &str) -> Vec<String> {
    text.lines()
        .filter_map(|line| {
            let rest = line.trim_start().strip_prefix('#')?.trim_start();
            let rest = rest.strip_prefix("include")?.trim();
            let (open, close) = match rest.chars().next()? {
                '"' => ('"', '"'),
                '<' => ('<', '>'),
                _ => return None,
            };
            let inner = rest.strip_prefix(open)?;
            Some(inner[..inner.find(close)?].to_string())
        })
        .collect()
}

fn cargo_package_name(text: &str) -> Option<String> {
    let mut in_package = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if in_package && let Some(value) = quoted_field(line, "name") {
            return Some(value);
        }
    }
    None
}

fn js_imports(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in text.lines() {
        for marker in [
            " from '",
            " from \"",
            "require('",
            "require(\"",
            "import('",
            "import(\"",
        ] {
            if let Some(start) = line.find(marker) {
                let rest = &line[start + marker.len()..];
                if let Some(end) = rest.find(['\'', '"']) {
                    out.push(rest[..end].to_string());
                }
            }
        }
    }
    out
}

fn resolve_js<'a>(path: &str, spec: &str, known: &BTreeSet<&'a str>) -> Option<&'a str> {
    if !spec.starts_with('.') {
        return None;
    }
    let mut parts: Vec<&str> = path.split('/').collect();
    parts.pop();
    for segment in spec.split('/') {
        match segment {
            "." | "" => {}
            ".." => {
                parts.pop()?;
            }
            other => parts.push(other),
        }
    }
    let base = parts.join("/");
    for suffix in [
        "",
        ".ts",
        ".tsx",
        ".js",
        ".jsx",
        ".mjs",
        "/index.ts",
        "/index.tsx",
        "/index.js",
    ] {
        if let Some(found) = known.get(format!("{base}{suffix}").as_str()) {
            return Some(found);
        }
    }
    None
}

/// `个文件`, or `file` / `files` by count.
fn unit(zh: bool, n: usize, cjk: &'static str, en: &'static str) -> String {
    match (zh, n) {
        (true, _) => cjk.to_string(),
        (false, 1) => en.to_string(),
        (false, _) => format!("{en}s"),
    }
}

